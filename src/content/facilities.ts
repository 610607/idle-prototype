export function getFacilityUpgradeCost(
  def: FacilityDef,
  currentLevel: number,
): { materials: number; parts: number; crystals: number; isBreakthrough: boolean } {
  const nextLevel = currentLevel + 1;
  const materials = Math.round(def.baseCostMaterials * Math.pow(def.costGrowth, currentLevel));
  const parts = def.baseCostParts
    ? Math.round(def.baseCostParts * Math.pow(def.costGrowth, currentLevel))
    : 0;
  const isBreakthrough =
    def.requiresBlueprint === true || (nextLevel > 1 && nextLevel % def.breakthroughEvery === 0);
  const crystals = isBreakthrough
    ? Math.round(def.baseCostCrystals * Math.pow(1.45, Math.floor(currentLevel / 2)))
    : 0;
  return { materials, parts, crystals, isBreakthrough };
}
